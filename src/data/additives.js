// Helper functions
export function getAdditiveById(id) {
  return BTP_ADDITIVES.find(a => a.id === id);
}

export function searchAdditives(query) {
  if (!query) return BTP_ADDITIVES;
  const q = query.toLowerCase().trim();
  return BTP_ADDITIVES.filter(a => {
    return a.name.toLowerCase().includes(q) ||
      a.insOrECode.toLowerCase().includes(q) ||
      a.function.toLowerCase().includes(q) ||
      a.alternativeNames.some(alt => alt.toLowerCase().includes(q)) ||
      a.searchKeywords.some(kw => kw.toLowerCase().includes(q));
  });
}
